/**
 * Builds the landing page images from the approved design sources in docs/design/landing
 * (the tablet image is a baked composite: the POS capture is warped onto the tablet photo):
 * AVIF + WebP + JPEG at a few widths, plus a typed manifest the components read.
 *
 *   pnpm --filter @app/site media
 *
 * Outputs (committed): public/landing/img/*, public/landing/video/*,
 * app/features/landing/landing-media.generated.ts
 */
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const siteRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const design = path.join(siteRoot, '../../docs/design/landing');
const imgOut = path.join(siteRoot, 'public/landing/img');
const videoOut = path.join(siteRoot, 'public/landing/video');

/** name -> source file, widths to emit. Widths never exceed the source width. */
const IMAGES = [
  { name: 'room', src: 'assets/p-room.jpg', widths: [800, 1280, 1920] },
  { name: 'tablet', src: 'assets/p-tablet-pos.jpg', widths: [800, 1280, 1920] },
  { name: 'pasta', src: 'assets/p-pasta.jpg', widths: [640, 1024, 1344] },
  { name: 'pass', src: 'assets/p-pass.jpg', widths: [640, 1024, 1344] },
  { name: 'tiramisu', src: 'assets/p-tiramisu.jpg', widths: [640, 1024] },
  { name: 'screen-products', src: 'assets/w-products.png', widths: [800, 1440] },
  { name: 'screen-modifiers', src: 'assets/w-modifiers.png', widths: [800, 1440] },
  { name: 'screen-branches', src: 'assets/w-branches.png', widths: [800, 1440] },
  { name: 'screen-billing', src: 'assets/w-billing.png', widths: [800, 1440] },
  { name: 'poster-pos', src: 'media/sahtain-pos-ar-poster.jpg', widths: [800, 1280] },
  { name: 'poster-kds', src: 'media/sahtain-kds-ar-poster.jpg', widths: [800, 1280] },
];

const VIDEOS = [
  { src: 'media/sahtain-pos-ar.webm', out: 'pos-ar.webm' },
  { src: 'media/sahtain-kds-ar.webm', out: 'kds-ar.webm' },
];

await mkdir(imgOut, { recursive: true });
await mkdir(videoOut, { recursive: true });

const manifest = {};
for (const item of IMAGES) {
  const source = path.join(design, item.src);
  const meta = await sharp(source).metadata();
  const widths = item.widths.filter((w) => w <= (meta.width ?? 0));
  for (const w of widths) {
    const base = sharp(source).resize({ width: w });
    const file = path.join(imgOut, `${item.name}-${w}`);
    await base.clone().avif({ quality: 52, effort: 4 }).toFile(`${file}.avif`);
    await base.clone().webp({ quality: 76 }).toFile(`${file}.webp`);
    await base.clone().jpeg({ quality: 80, mozjpeg: true }).toFile(`${file}.jpg`);
  }
  manifest[item.name] = { width: meta.width, height: meta.height, widths };
  console.log(item.name, `${meta.width}x${meta.height}`, widths.join(','));
}

for (const v of VIDEOS) {
  await copyFile(path.join(design, v.src), path.join(videoOut, v.out));
}

const body = `// Generated by scripts/build-landing-media.mjs. Do not edit by hand.
export type LandingImageName =
${Object.keys(manifest)
  .map((n) => `  | '${n}'`)
  .join('\n')};

export type LandingImageMeta = {
  /** Intrinsic size of the source image (sets the aspect ratio). */
  width: number;
  height: number;
  /** Widths emitted as \`/landing/img/<name>-<width>.(avif|webp|jpg)\`. */
  widths: readonly number[];
};

export const LANDING_IMAGES: Record<LandingImageName, LandingImageMeta> = {
${Object.entries(manifest)
  .map(
    ([n, m]) =>
      `  '${n}': { width: ${m.width}, height: ${m.height}, widths: [${m.widths.join(', ')}] },`,
  )
  .join('\n')}
};
`;
await writeFile(path.join(siteRoot, 'app/features/landing/landing-media.generated.ts'), body, 'utf8');
console.log('manifest written');
